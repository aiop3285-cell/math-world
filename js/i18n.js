  var lang = localStorage.getItem("mw_lang") || "ar";

  function t(key, vars) {
    var val = (dict[lang] && dict[lang][key]) || dict.ar[key] || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        val = val.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
      });
    }
    return val;
  }

  function pick(obj) {
    if (obj == null) return "";
    if (typeof obj === "string") return obj;
    return obj[lang] != null ? obj[lang] : obj.ar || obj.en || "";
  }

  function setLang(l) {
    lang = l === "en" ? "en" : "ar";
    localStorage.setItem("mw_lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }

  setLang(lang);

  window.MW = window.MW || {};
  MW.i18n = { t: t, pick: pick, setLang: setLang };
